import json
from pathlib import Path
from typing import List
from urllib.parse import urlparse, unquote

import requests

from .config import *


LS_JSON_DIR = Path(LS_JSON_OUTPUT_DIR)
PRESIGNED_URL_DIR = Path(PRESIGNED_URL_OUTPUT_DIR)


def _ls_headers():
    return {"Authorization": f"Token {LS_REFRESH_TOKEN}"}


def get_project_id_by_title(title: str) -> int:
    """Find a Label Studio project ID by its title. Creates it if not found."""
    resp = requests.get(
        f"{LS_BASE}/api/projects",
        headers=_ls_headers(),
    )
    resp.raise_for_status()

    projects = resp.json().get("results", [])
    for project in projects:
        if project["title"] == title:
            return project["id"]

    # project not found — create it
    resp = requests.post(
        f"{LS_BASE}/api/projects",
        headers=_ls_headers(),
        json={"title": title},
    )
    resp.raise_for_status()
    return resp.json()["id"]


def push_prediction(project_id: int, png_filename: str, prediction: dict, png_url_map: dict):
    """Import one task into Label Studio: an image plus its OCR prediction."""

    # find the presigned URL by matching the filename
    fileuri = None
    for path_key, url in png_url_map.items():
        if Path(path_key).name == png_filename:
            fileuri = url
            break

    if not fileuri:
        raise ValueError(f"No presigned URL found for: {png_filename}")

    payload = [{
        "data": {"ocr": fileuri},
        "predictions": [{
            "result": prediction["result"],
            "model_version": "ocr-prelabel-v1",
        }],
    }]

    resp = requests.post(
        f"{LS_BASE}/api/projects/{project_id}/import",
        headers=_ls_headers(),
        json=payload,
    )
    resp.raise_for_status()


def push_predictions_to_ls():
    """Import every staged prediction in ls_json/*.jsonl into Label Studio."""

    # load presigned URLs generated by export_png_to_minio (one JSON per image)
    if not PRESIGNED_URL_DIR.exists() or not any(PRESIGNED_URL_DIR.glob("*.json")):
        raise FileNotFoundError(f"No presigned URL files found in: {PRESIGNED_URL_DIR}. Run export_png_to_minio first.")

    png_url_map = {}
    for url_file in PRESIGNED_URL_DIR.glob("*.json"):
        png_url_map.update(json.loads(url_file.read_text()))

    project_id = get_project_id_by_title(PROJECT_NAME)

    jsonl_files = sorted(LS_JSON_DIR.glob("*.jsonl"))
    seen = set()

    pushed = 0
    skipped = 0

    for jsonl_path in jsonl_files:
        with jsonl_path.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue

                rec = json.loads(line)
                png_filename = rec["png_filename"]
                prediction = rec["prediction"]

                if png_filename in seen:
                    skipped += 1
                    continue
                seen.add(png_filename)

                push_prediction(project_id, png_filename, prediction, png_url_map)
                pushed += 1

    print(f"[DONE] pushed={pushed}, skipped={skipped}, project_id={project_id}")

    # After pushing, fetch annotations back from Label Studio
    fetch_ls_annotations(project_id)


def fetch_ls_annotations(project_id: int) -> List[Path]:
    """Fetch all tasks (with annotations) from Label Studio and save to ANNOTATION_OUTPUT_DIR."""
    ANNOTATION_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    exported = 0
    out_files = []
    page = 1

    while True:
        resp = requests.get(
            f"{LS_BASE}/api/tasks",
            headers=_ls_headers(),
            params={"project": project_id, "page": page, "page_size": LS_PAGESIZE},
        )
        resp.raise_for_status()
        data = resp.json()

        summaries = data.get("tasks") or data.get("results") or []
        if not summaries:
            break

        for s in summaries:
            task_id = s.get("id")
            if not task_id:
                continue

            full_resp = requests.get(
                f"{LS_BASE}/api/tasks/{task_id}",
                headers=_ls_headers(),
                params={"fields": "all"},
            )
            full_resp.raise_for_status()
            task = full_resp.json()

            ocr_url = (task.get("data") or {}).get("ocr", "")
            img_stem = Path(unquote(urlparse(ocr_url).path)).stem if ocr_url else str(task_id)

            out_path = ANNOTATION_OUTPUT_DIR / f"{img_stem}.json"
            out_path.write_text(json.dumps(task, ensure_ascii=False, indent=2), encoding="utf-8")
            exported += 1
            out_files.append(out_path)

        if len(summaries) < LS_PAGESIZE:
            break
        page += 1

    print(f"[DONE] fetch_ls_annotations: exported={exported}, dir={ANNOTATION_OUTPUT_DIR}")
    return out_files